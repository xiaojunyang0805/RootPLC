/// A construct the C back end does not support yet ([build.c.subset]).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Unsupported {
    /// IR file index of the definition that uses it.
    pub file: usize,
    /// Byte offset in that file (0 when unknown).
    pub offset: u32,
    /// What it is.
    pub construct: String,
}

type R<T> = Result<T, Unsupported>;

/// The value domain of a C expression.
